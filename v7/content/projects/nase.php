        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">An HCI course project that became personal. I audited NASE page by page, ranked every problem by severity and redesigned the components that failed.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>23 issues found</b>: across 5 pages, each mapped to a WCAG 2.1 criterion</li>
<li><b>Keyboard first</b>: every control reachable with a visible focus outline</li>
<li><b>Screen reader ready</b>: semantic HTML and ARIA labels, tested with NVDA and VoiceOver</li>
<li><b>Readable contrast</b>: 4.5:1 or better on all text, checked with an automated pipeline</li>
</ul>
        </div>
