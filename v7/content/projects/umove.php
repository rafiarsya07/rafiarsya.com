        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">No UM student should skip a meal because the cafe is too far or class ran late. You say what to buy and from where, set a fee from RM1, and a student who is already nearby takes it.</p>
<figure class="rf-figure-lg"><img alt="Three taps: post a request, a runner takes it, pay on arrival" decoding="async" loading="lazy" src="image/assets/umove/how-it-works.png"/><figcaption class="img-caption">Post, get a runner, pay on arrival</figcaption></figure>
        </div>
        <br>

        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Live board</b>: new requests reach every runner the moment they are posted.</li>
<li><b>Checked runners</b>: every runner is a verified UM student before they can take a run.</li>
<li><b>Safe handover</b>: a 4 digit code closes each delivery, then both sides rate each other.</li>
<li><b>Alerts</b>: push notifications and a Telegram bot, so runners hear about requests with the app closed.</li>
</ul>
        </div>
