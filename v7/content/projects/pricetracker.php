        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">Most price trackers need a scraping service, a server and a scheduler. This one runs entirely inside Chrome, so it costs nothing and your data never leaves your computer.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Works on any shop</b>: click the price once and the extension remembers where it is</li>
<li><b>Checks in the background</b>: the real page is loaded, so prices rendered by JavaScript work too</li>
<li><b>Instant alerts</b>: a Chrome notification when the price drops</li>
<li><b>Free and private</b>: storage, scheduling and notifications all use Chrome itself</li>
</ul>
