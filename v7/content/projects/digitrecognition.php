        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">No deep learning framework, only NumPy. Writing the forward pass, backpropagation and the optimiser myself is how I learned what a framework normally hides.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Built from scratch</b>: convolution, pooling, dense layers and Adam in NumPy</li>
<li><b>Trained on real MNIST</b>: 60,000 training images, parsed from the raw files</li>
<li><b>Canvas to MNIST</b>: drawings are cropped, scaled and centred like the training data</li>
<li><b>See it think</b>: a saliency map and live probability bars</li>
</ul>
