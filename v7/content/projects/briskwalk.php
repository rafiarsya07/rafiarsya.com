        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">Participants sign up, pay and upload proof of payment in one short form on their phone. The committee checks everything in a Google Sheet they already know.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>One mobile form</b>: details first, then a QR code and bank details to pay without leaving the page</li>
<li><b>Smaller uploads</b>: payment screenshots are resized and converted to WebP in the browser</li>
<li><b>No server</b>: Google Apps Script writes each entry to Sheets and the proof to Drive</li>
<li><b>Free to run</b>: nothing to host or pay for</li>
</ul>
        </div>
