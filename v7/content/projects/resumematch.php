        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">How well does my resume fit this job? Resume Match answers that without sending anything to an AI API, and shows exactly why it gave the score.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Synonym matching</b>: React, ReactJS and react.js count as the same skill</li>
<li><b>Required vs nice to have</b>: the job post is split, and required skills weigh more</li>
<li><b>Experience and education</b>: phrases like 3+ years are detected, in English and Malay</li>
<li><b>PDF in, report out</b>: both documents can be uploaded as PDF</li>
</ul>
