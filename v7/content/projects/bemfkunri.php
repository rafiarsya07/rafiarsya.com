        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">The board needed a site its own team can keep up to date. News, agenda, programmes, the board and contact details all come from a shared Google Sheet, so a new post is just a new row.</p>
        </div>
        <br>

        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>No-code updates</b>: the board edits news, agenda and members from a Google Sheet</li>
<li><b>Agenda that syncs</b>: events can be saved to Google Calendar in one tap</li>
<li><b>Fast and mobile first</b>: a light static site with smooth transitions</li>
</ul>
