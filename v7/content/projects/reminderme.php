        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">Pendamping (Indonesian for companion) knows my day and shows the one or two things that matter right now, from the nearest deadline to the next prayer time.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Smart home screen</b>: nudges ranked by urgency, so the important thing comes first</li>
<li><b>Exam countdowns</b>: reminders that get louder as an exam gets closer</li>
<li><b>Works offline</b>: all data stays on the phone, with export and import</li>
<li><b>Real Android app</b>: the same web app wrapped as a signed APK</li>
</ul>
        </div>
