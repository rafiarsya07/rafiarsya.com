        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">A Java long overflows after about 9.2 quintillion. This WIA1002 group project stores numbers digit by digit, so they can be as long as memory allows.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Own data structure</b>: a doubly linked list with only the operations the maths needs</li>
<li><b>Four operations</b>: addition, subtraction, multiplication and long division</li>
<li><b>Edge cases handled</b>: leading zeros, division by zero and invalid input</li>
<li><b>Step by step</b>: a visualizer that animates each operation</li>
</ul>
