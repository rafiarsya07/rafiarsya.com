        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">SENARA Creative Artfest shows work by young artists from Indonesia and Malaysia. This year the site carries the Instellar X Senara identity and lets visitors browse the artworks online.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Online Exhibition</b>: every artwork with its own page and next and previous navigation</li>
<li><b>Hero that fits any screen</b>: separate artwork for wide, standard and portrait screens instead of cropping</li>
<li><b>Faithful to the design</b>: sizes measured from the mockups and converted to fluid units</li>
<li><b>Lighter pages</b>: text lifted out of flat images, buttons rebuilt in CSS</li>
</ul>
        </div>
