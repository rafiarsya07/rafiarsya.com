        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">IDFEST brings Indonesian culture to Universiti Malaya. As part of the website committee, I turned the Figma designs into the live site.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Figma to code</b>: pages built closely from the design team's mockups</li>
<li><b>Reusable sections</b>: shared components, including an animated mascot used across pages</li>
<li><b>Tuned for every screen</b>: hero and timeline built separately for phone and desktop</li>
<li><b>Team workflow</b>: branches and pull requests, reviewed before merging</li>
</ul>
