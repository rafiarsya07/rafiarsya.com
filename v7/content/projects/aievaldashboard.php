        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">Change a prompt and you want to know if the model got better or worse. Instead of eyeballing answers, this tool runs a saved test set and grades every answer the same way.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>AI judge</b>: each answer is graded against the expected one, with a one-line reason</li>
<li><b>More than accuracy</b>: latency and cost recorded for every test case</li>
<li><b>Repeatable runs</b>: the same test set can be replayed against a new model or prompt</li>
<li><b>Clear results</b>: a verdict breakdown chart for each run</li>
</ul>
