        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">Your webcam becomes a canvas. Raise your index finger to draw, and hover over on-screen buttons to change colour, start, stop or clear.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Hand tracking</b>: MediaPipe finds 21 landmarks per hand, up to 4 hands at once</li>
<li><b>Gesture controls</b>: every action is triggered by your fingertip, no mouse or keyboard</li>
<li><b>Four brushes</b>: blue, green, red and pink</li>
<li><b>Real time</b>: OpenCV draws straight onto the live video</li>
</ul>
        </div>
