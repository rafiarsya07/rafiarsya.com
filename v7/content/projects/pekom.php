        <h3>01 The Idea</h3>
        <div class="blog-content-body">
<p class="p-text">PEKOM runs Code Fest, Mental Health Week, IS 101 and UMHackathon. The site gives freshers, members and sponsors one place to find all of it, and it is easy for next year's committee to keep up to date. I built it from the first scaffold to every page.</p>
        </div>
        <br>
        <h3>02 Highlights</h3>
        <div class="blog-content-body">
<ul>
<li><b>Content as data</b>: events, news, members and merch live in typed files, so updates need no code changes</li>
<li><b>Fully static</b>: every page is prerendered, including one page per event</li>
<li><b>Three languages</b>: English, Bahasa Malaysia and Chinese</li>
<li><b>Polished details</b>: a story-style photo viewer and smooth motion</li>
</ul>
        </div>
